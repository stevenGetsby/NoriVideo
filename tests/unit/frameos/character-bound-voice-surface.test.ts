import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'

function source(relativePath: string) {
  return fs.readFileSync(path.join(process.cwd(), relativePath), 'utf8')
}

describe('character-bound voice workflow', () => {
  it('binds uploaded or Seedance audition audio directly to each character', () => {
    const timbre = source('src/components/frameos/views/FosTimbre.tsx')
    const overview = source('src/components/frameos/views/FosWorkbenchOverview.tsx')
    const projectHook = source('src/components/frameos/useFosProject.ts')
    const assetLibrary = source('src/components/frameos/views/FosAssetLibrary.tsx')
    const materialLibrary = source('src/components/frameos/views/FosMaterialLibrary.tsx')
    const auditionRoute = source('src/app/api/novel-promotion/[projectId]/character-audition/route.ts')
    const characterVoiceRoute = source('src/app/api/novel-promotion/[projectId]/character-voice/route.ts')
    const videoWorker = source('src/lib/workers/video.worker.ts')
    const toolboxVideoWorker = source('src/lib/workers/handlers/toolbox-video-task-handler.ts')
    const audioExtractor = source('src/lib/media/video-audio.ts')

    expect(timbre).not.toContain('音色库选择')
    expect(timbre).not.toContain('候选音色')
    expect(timbre).toContain('本地 MP3 上传')
    expect(timbre).toContain('/character-audition')
    expect(timbre).toContain('/character-voice')
    expect(auditionRoute).toContain('generateAudio: true')
    expect(auditionRoute).toContain('referenceImages: [referenceImage]')
    expect(auditionRoute).toContain('referenceImageNames: [character.name]')
    expect(auditionRoute).toContain("inputMode: 'reference'")
    expect(auditionRoute).toContain('TASK_TYPE.TOOLBOX_VIDEO')
    expect(characterVoiceRoute).toContain('customVoiceMediaId')
    expect(toolboxVideoWorker).toContain("asset.bizType === 'character_audition'")
    expect(toolboxVideoWorker).toContain('extractVoiceAudioFromVideo')
    expect(toolboxVideoWorker).not.toContain("voiceType: 'seedance-audition'")
    expect(timbre).toContain('确认并绑定音色')
    expect(timbre).toContain('useAccountBalance')
    expect(timbre).toContain("if (!generationAllowed) { setError(generationDisabledReason || '当前账号不可生成'); return }")
    expect(timbre).toContain('generationDisabledLabel')
    expect(timbre).toContain('CompactAudioPlayer')
    expect(timbre).toContain('toPlayableAudioUrl')
    expect(timbre).toContain('fos-timbre-studio-grid')
    expect(audioExtractor).toContain("'-map', '0:a:0'")
    expect(videoWorker).toContain('resolvePanelAudioReferencesForVideo')
    expect(videoWorker).toContain('usesArkReferenceImageMode')
    expect(videoWorker).toContain('usesArkReferenceMediaMode')
    expect(videoWorker).toContain('generateAudio: true')
    expect(overview).toContain('boundVoiceCount')
    expect(overview).toContain('`角色音色 ${boundVoiceCount}/${charCount}`')
    expect(overview).not.toContain('`角色音色 0/${charCount}`')
    expect(projectHook).toContain('projectDataCache.delete(cacheKey)')
    expect(assetLibrary).toContain('asset.voice.media?.url || asset.voice.customVoiceUrl')
    expect(assetLibrary).toContain('nori-voice-badge-bound')
    expect(assetLibrary).toContain('nori-voice-badge-missing')
    expect(assetLibrary).toContain('只看缺音色')
    expect(assetLibrary).toContain('音色 {voiceBoundCount}/{displayed.length}')
    expect(assetLibrary).toContain('设置角色音色')
    expect(materialLibrary).toContain('fml-voice-badge')
    expect(materialLibrary).toContain('缺音色')
    expect(materialLibrary).toContain('/workspace/asset-hub')
    expect(timbre).toContain('批量按角色名绑定')
    expect(timbre).toContain('batch-character-voices')
    expect(assetLibrary).toContain('<audio src={toPlayableAudioUrl(asset.voice.url) || asset.voice.url}')
  })

  it('surfaces voice binding in the toolbox, picker, and canvas without clipped badges', () => {
    const toolbox = source('src/components/frameos/views/FosToolbox.tsx')
    const picker = source('src/components/frameos/materials/MaterialPickerDialog.tsx')
    const characterVoice = source('src/components/frameos/materials/character-voice.ts')
    const workTrace = source('src/components/frameos/views/toolbox-work-trace.ts')
    const workTraceCard = source('src/components/frameos/views/ToolboxWorkTraceCard.tsx')
    const canvasGenerator = source('src/features/canvas/components/CanvasGenerator.tsx')
    const canvasAssets = source('src/features/canvas/components/CanvasProjectAssets.tsx')

    expect(characterVoice).toContain("frameosAssetCategoryFromMetadata(material.metadata) !== 'character'")
    expect(characterVoice).toContain('characterVoiceBindingStats')
    expect(picker).toContain('characterVoiceBindingState(material)')
    expect(picker).toContain('material-picker-voice-badge')
    expect(picker).toContain('visibleVoiceStats.bound}/{visibleVoiceStats.total')
    expect(toolbox).toContain('characterVoiceBindingState(material)')
    expect(toolbox).toContain('角色音色 ${characterVoiceStats.bound}/${characterVoiceStats.total}')
    expect(toolbox).toContain('hintTone')
    expect(toolbox).toContain('defaultToolboxInputMode(activeType)')
    expect(toolbox).toContain('formatToolboxWorkTrace')
    expect(workTraceCard).toContain('工作留痕')
    expect(toolbox).toContain('copyTraceText')
    expect(workTraceCard).toContain('trace.costLabel')
    expect(toolbox).toContain('toolbox-work-trace')
    expect(workTrace).toContain('全能参考（图片 / 视频 / 音色）')
    expect(workTrace).toContain('文生视频（仅提示词）')
    expect(workTrace).toContain('formatToolboxWorkTrace')
    expect(canvasGenerator).toContain('nori-canvas-generator-ref-voice')
    expect(canvasGenerator).toContain('全能参考将自动带入')
    expect(canvasGenerator).toContain('is-muted')
    expect(canvasGenerator).toContain('is-warning')
    expect(canvasAssets).toContain('missingVoiceCount')
    expect(canvasAssets).toContain('nori-canvas-project-assets-voice')
  })
})
