import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'

function source(relativePath: string) {
  return fs.readFileSync(path.join(process.cwd(), relativePath), 'utf8')
}

describe('project entry and video review surface', () => {
  it('keeps projects enterable while import work continues', () => {
    const panels = source('src/components/frameos/works/FosWorkPanels.tsx')
    const styles = source('src/styles/frameos-replica.css')
    expect(panels).toContain('data-testid="project-background-task-status"')
    expect(panels).toContain('className="works-project-running-enter"')
    expect(panels).toContain('后台任务不影响进入作品')
    expect(panels).toContain('episodeCount === 0')
    expect(styles).toMatch(/\.works-project-running \{[^}]*pointer-events: none/)
    expect(styles).toMatch(/\.works-project-running-enter \{[^}]*pointer-events: auto/)
  })

  it('exposes a stable parent entry in regular panels and both canvas chrome states', () => {
    const header = source('src/components/frameos/FosProjectHeader.tsx')
    const canvas = source('src/features/canvas/components/CanvasChrome.tsx')
    const emptyCanvas = source('src/features/canvas/components/EmptyCanvasChrome.tsx')
    expect(header).toContain('data-testid="project-panel-back"')
    expect(header).toContain("backLabel || '返回上一级'")
    expect(header).toContain('href={backTo ??')
    expect(header).not.toContain('pathname: backTo')
    expect(canvas).toContain('data-testid="canvas-parent-back"')
    expect(emptyCanvas).toContain('data-testid="empty-canvas-parent-back"')
  })

  it('reflows project context and actions instead of crushing tags on small screens', () => {
    const header = source('src/components/frameos/FosProjectHeader.tsx')
    const styles = source('src/styles/frameos-replica.css')

    expect(header).toContain('className="fos-stage-context')
    expect(header).toContain('className="fos-stage-actions')
    expect(styles).toContain('.fos-stage-context > h1 { min-width: 0; max-width: 100%; flex: 0 1 auto; white-space: normal; overflow-wrap: anywhere; }')
    expect(styles).toContain('.fos-meta-tag { flex: none; white-space: nowrap; }')
    expect(styles).toMatch(/@media \(max-width: 900px\) \{[\s\S]*?\.fos-stage-header \{[\s\S]*?grid-template-columns: auto minmax\(0,1fr\)/)
    expect(styles).toMatch(/\.fos-stage-actions \{[\s\S]*?grid-column: 1 \/ -1;[\s\S]*?flex-wrap: wrap;/)
  })

  it('uses an episode submission workspace for Segment and combined-video review', () => {
    const client = source('src/components/frameos/FosAssignmentsClient.tsx')
    const table = source('src/components/frameos/FosAssignmentsTable.tsx')
    const workspace = source('src/components/frameos/FosVideoReviewWorkspace.tsx')
    const reviewPage = source('src/app/[locale]/my-assignments/[assignmentId]/video-review/page.tsx')
    const timeline = source('src/components/frameos/views/FosProduction.tsx')
    const shotProduction = source('src/components/frameos/views/FosProductionShot.tsx')
    const assignments = source('src/lib/collaboration/assignments.ts')
    const reviewService = source('src/lib/collaboration/video-review.ts')
    const assignmentViewModel = source('src/components/frameos/assignments-view-model.ts')
    const styles = source('src/styles/frameos-replica.css')

    expect(reviewPage).toContain('<FosVideoReviewWorkspace')
    expect(client).toContain('pathname: assignmentDestination(assignment)')
    expect(assignmentViewModel).toContain('`/my-assignments/${assignment.id}/video-review`')
    expect(table).toContain("assignment.stage !== 'video'")
    expect(workspace).toContain('整集连续预览')
    expect(workspace).toContain('onEnded={handleEnded}')
    expect(workspace).toContain("selectedSource?.virtualSequence")
    expect(workspace).toContain('playbackSource?.trimStartMs')
    expect(workspace).toContain('playbackSource?.trimEndMs')
    expect(workspace).toContain('videoAnnotations: drafts.map')
    expect(workspace).toContain('分镜内容')
    expect(workspace).toContain('生视频提示词')
    expect(workspace).toContain('className="fvr-prompt-wide"')
    expect(workspace).toContain('进入分镜制作')
    expect(workspace).toContain('发布修改意见')
    expect(workspace).toContain('审核通过')
    expect(workspace).toContain('整集修改意见')
    expect(workspace).toContain('function ReviewRangeSlider')
    expect(workspace).toContain('aria-label="评审开始时间"')
    expect(workspace).toContain('aria-label="评审结束时间"')
    expect(workspace).toContain("onPointerUp={(event) => onCommit('start', Number(event.currentTarget.value))}")
    expect(workspace).toContain("onPointerUp={(event) => onCommit('end', Number(event.currentTarget.value))}")
    expect(workspace).toContain('整集预览 · 多段标注')
    expect(workspace).toContain('所有时间码均对应整集时间轴')
    expect(workspace).toContain('aria-label="整集多段评审批注"')
    expect(workspace).toContain('annotationMarkerStyle(annotation)')
    expect(workspace).toContain('onClick={() => seekEpisodeToSegment(source)}')
    expect(workspace).not.toContain('onClick={() => selectSource(source)}')
    expect(workspace).not.toContain('Segment 评审')
    expect(workspace).toContain('const annotationPanelId = containingSegment?.panelId || null')
    expect(workspace).toContain('panelId: annotationPanelId')
    expect(workspace).toContain('startMs: rangeStartMs')
    expect(workspace).toContain('endMs: rangeEndMs')
    expect(styles).toContain(".fvr-range-slider input[type='range']")
    expect(styles).toContain(".fvr-range-slider input[type='range']::-webkit-slider-thumb")
    expect(styles).toContain('.fvr-annotation-lane > button')
    expect(workspace).toContain("router.push({ pathname: '/my-assignments'")
    expect(timeline).not.toContain('VideoReviewFeedback')
    expect(shotProduction).not.toContain('submitEpisode()')
    expect(shotProduction).toContain('进入剪辑与提交评审')
    expect(shotProduction).toContain("['review', `评审意见")
    expect(shotProduction).toContain('整集评审意见')
    expect(shotProduction).toContain("params.append('status', 'queued')")
    expect(shotProduction).toContain("params.append('status', 'processing')")
    expect(assignments).toContain('reviewSubmission: videoReviewSubmission')
    expect(assignments).toContain('validateVideoReviewAnnotationsAgainstSnapshot')
    expect(reviewService).toContain("kind: 'episode' as const")
    expect(reviewService).toContain("kind: 'segment' as const")
  })

  it('keeps storyboard as a production assignment and does not open a review workspace', () => {
    const viewModel = source('src/components/frameos/assignments-view-model.ts')
    const assignments = source('src/lib/collaboration/assignments.ts')
    const policy = source('src/lib/collaboration/assignment-policy.ts')

    expect(policy).toContain("return stage === 'storyboard'")
    expect(assignments).toContain('assignmentStageSkipsReview(row.stage)')
    expect(assignments).toContain("stage: { not: 'storyboard' }")
    expect(viewModel).not.toContain('`/my-assignments/${assignment.id}/storyboard-review`')
    expect(viewModel).not.toContain("return '审核本集分镜内容'")
    expect(viewModel).toContain('${base}/storyboard')
  })

  it('submits review from a saved edit instead of the Segment generation panel', () => {
    const production = source('src/components/frameos/views/FosProductionShot.tsx')
    const assembly = source('src/components/frameos/views/FosAssemblyEditor.tsx')
    const timeline = source('src/components/frameos/views/FosAssemblyTimeline.tsx')
    const modelSection = production.indexOf('>模型配置</h3>')
    const generateAction = production.indexOf('onClick={() => void generate()}', modelSection)

    expect(modelSection).toBeGreaterThan(-1)
    expect(generateAction).toBeGreaterThan(modelSection)
    expect(production).toContain('{readyVideoCount} / {shots.length} 个 Segment 可用')
    expect(production).toContain('剪辑保存后即可提交全集评审')
    expect(production).not.toContain('submitEpisodeLabel')
    expect(assembly).toContain('const needsSave = !hasSavedProject || isDirty')
    expect(assembly).toContain('&& !needsSave')
    expect(assembly).toContain('剪辑已保存，可以提交')
    expect(assembly).toContain("if (event.code === 'Space')")
    expect(assembly).toContain('if (timelineState.playing) pause()')
    expect(assembly).toContain("event.key.toLowerCase() === 'c'")
    expect(assembly).toContain('Space 播放 / 暂停')
    expect(assembly).toContain('C 切割')
    expect(timeline).toContain('<kbd>C</kbd>')
  })

  it('never exposes internal progress keys or Prisma worker stacks as product copy', () => {
    const overview = source('src/components/frameos/views/FosWorkbenchOverview.tsx')
    const storyboard = source('src/components/frameos/views/FosStoryboard.tsx')
    const canvasProgress = source('src/features/canvas/components/CanvasOperationTaskProgress.tsx')

    expect(overview).toContain("'progress.runtime.llm.completed': '模型输出完成'")
    expect(overview).toContain('productTaskError(')
    expect(overview).not.toContain('导出交付')
    expect(overview).not.toContain('ExportDeliveryDialog')
    expect(storyboard).toContain("'progress.runtime.llm.completed': '模型输出完成'")
    expect(storyboard).toContain('friendlyStoryboardTaskError')
    expect(canvasProgress).toContain("/^(?:progress\\.|[a-z][\\w.-]*_[\\w.-]+)/i")
  })

  it('keeps Segment generation and the full editor as two parts of production', () => {
    const production = source('src/components/frameos/views/FosProduction.tsx')
    const productionShot = source('src/components/frameos/views/FosProductionShot.tsx')
    const productionTabs = source('src/components/frameos/views/FosProductionModeTabs.tsx')
    const assembly = source('src/components/frameos/views/FosAssemblyEditor.tsx')
    const workflow = source('src/components/frameos/FosWorkflowClient.tsx')
    const editorRoute = source('src/app/api/novel-promotion/[projectId]/editor/route.ts')

    expect(production).not.toContain('S01 柴房')
    expect(production).toContain('分镜生成')
    expect(production).toContain('production/timeline')
    expect(production).toContain('>剪辑</Link>')
    expect(productionTabs).toContain("label: '分镜生成'")
    expect(productionTabs).toContain("label: '剪辑'")
    expect(productionTabs).toContain('分镜生成 → 剪辑 → 提交评审')
    expect(productionShot).toContain('active="generate"')
    expect(productionShot).not.toContain('<FosRoughCutStrip')
    expect(assembly).toContain('active="edit"')
    expect(assembly).toContain('<FosAssemblyTimeline')
    expect(workflow).toContain('<FosAssemblyEditor data={data} initialEpisodeId={initialEpisodeId} />')
    expect(editorRoute).toContain('normalizeRoughCutProject')
    expect(editorRoute).toContain('outputUrl: null')
  })

  it('keeps episode feedback and final confirmation inside the assembly workspace', () => {
    const assembly = source('src/components/frameos/views/FosAssemblyEditor.tsx')
    const styles = source('src/styles/frameos-replica.css')

    expect(assembly).toContain('data-testid="assembly-review-panel"')
    expect(assembly).toContain('整集修改意见')
    expect(assembly).toContain('aria-label="整集评审开始时间"')
    expect(assembly).toContain('aria-label="整集评审结束时间"')
    expect(assembly).toContain('添加时段意见')
    expect(assembly).toContain('发布修改意见')
    expect(assembly).toContain('确认整集视频')
    expect(assembly).toContain("apiFetch(`/api/collaboration/assignments/${action}`")
    expect(assembly).toContain('videoAnnotations: reviewDrafts.map')
    expect(assembly).toContain('await review.reload()')
    expect(assembly).not.toContain('/my-assignments/')
    expect(assembly).not.toContain('onOpenReview')
    expect(styles).toContain('Assembly editor v3: FrameOS-proportioned workspace with in-project review.')
    expect(styles).toContain('.fac-review-panel {')
    expect(styles).toContain('grid-template-columns:minmax(300px,.82fr) minmax(520px,1.45fr) minmax(310px,.78fr)')
  })
})
